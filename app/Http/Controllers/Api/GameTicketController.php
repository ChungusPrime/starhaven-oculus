<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\Character;
use App\Models\GameTicket;
use Illuminate\Auth\AuthenticationException;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;

class GameTicketController extends Controller
{
    private const INVALID_TICKET_MESSAGE = 'Invalid or expired game ticket.';

    public function store(Request $request): JsonResponse
    {
        // The player authenticates this request with their normal Oculus access
        // token. A valid access token alone is not enough: the token must also
        // have the explicit ability to create game tickets. This lets Oculus
        // issue limited access tokens that cannot be exchanged for game access.
        $user = $request->user();

        if (! $user->tokenCan('game-ticket:create')) {
            abort(403, 'This access token cannot create game tickets.');
        }

        if (! $user->activeCharacter()->exists()) {
            abort(409, 'Create an active character before joining a universe.');
        }

        // A ticket has two pieces: a public database UUID and a secret. Only the
        // SHA-256 hash of the secret is stored in the database. The plaintext
        // secret is returned once, in this response, and Oculus cannot recover
        // it later. This follows the same basic pattern as password storage.
        $secret = Str::random(64);
        $secretHash = hash('sha256', $secret);

        // The default lifetime is 60 seconds. The short lifetime limits how long
        // a stolen ticket is useful, which is why the Phaser client requests it
        // only after the player clicks Play rather than when they first log in.
        $expirationSeconds = (int) config('oculus.game_ticket_expiration_seconds');
        $expiresAt = now()->addSeconds($expirationSeconds);

        // This row is the authoritative server-side ticket record. The UUID is
        // generated by the GameTicket model's HasUuids trait. consumed_at starts
        // as NULL and will be filled in after the first successful use.
        $ticket = GameTicket::create([
            'user_id' => $user->id,
            'token_hash' => $secretHash,
            'expires_at' => $expiresAt,
        ]);

        // The client receives "UUID.secret". The UUID tells Oculus which row to
        // load later; the secret proves that the caller possesses the ticket.
        // Do not log this value because it is a short-lived bearer credential.
        $plainTextTicket = $ticket->id.'.'.$secret;

        return response()->json([
            'data' => [
                'ticket' => $plainTextTicket,
                'expires_at' => $expiresAt->toISOString(),
            ],
        ], 201);
    }

    /**
     * @throws AuthenticationException
     */
    public function consume(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'ticket' => ['required', 'string', 'max:128'],
        ]);

        [$ticketId, $secret] = $this->parseTicket($validated['ticket']);
        [$ticket, $character] = DB::transaction(
            fn (): array => $this->consumeTicket($ticketId, $secret)
        );
        $user = $ticket->user;

        return response()->json([
            'data' => compact('user', 'character'),
        ]);
    }

    /**
     * @return array{string, string}
     *
     * @throws AuthenticationException
     */
    private function parseTicket(string $plainTextTicket): array
    {
        $parts = explode('.', $plainTextTicket);

        if (count($parts) !== 2 || ! Str::isUuid($parts[0]) || $parts[1] === '') {
            $this->rejectTicket();
        }

        return [$parts[0], $parts[1]];
    }

    /**
     * @return array{GameTicket, Character}
     *
     * @throws AuthenticationException
     */
    private function consumeTicket(string $ticketId, string $secret): array
    {
        // The row lock keeps validation and one-time consumption atomic.
        $ticket = GameTicket::query()->lockForUpdate()->find($ticketId);

        if ($ticket === null
            || $ticket->consumed_at !== null
            || $ticket->expires_at->isPast()
            || ! hash_equals($ticket->token_hash, hash('sha256', $secret))) {
            $this->rejectTicket();
        }

        $character = $ticket->user->activeCharacter()->first();

        if ($character === null) {
            $this->rejectTicket();
        }

        $ticket->update(['consumed_at' => now()]);

        return [$ticket, $character];
    }

    /**
     * @throws AuthenticationException
     */
    private function rejectTicket(): never
    {
        throw new AuthenticationException(self::INVALID_TICKET_MESSAGE);
    }
}
